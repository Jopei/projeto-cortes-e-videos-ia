from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import JSON, Boolean, ForeignKey, String, Text, UniqueConstraint, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db import Base
from app.models.enums import Platform, platform_enum


class ClipMetadata(Base):
    """Per-platform title/description/hashtags for a Clip.

    One row per (clip_id, platform) — generated by
    `POST /api/clips/{id}/metadata/regenerate` (LLM, etapa C) and editable via
    `PUT /api/clips/{id}/metadata/{platform}`, which also sets `edited=True`
    so a later regenerate doesn't silently clobber a human edit without the
    caller knowing.
    """

    __tablename__ = "clip_metadata"
    __table_args__ = (UniqueConstraint("clip_id", "platform", name="uq_clip_metadata_clip_platform"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4)
    clip_id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), ForeignKey("clips.id"), nullable=False, index=True)
    platform: Mapped[Platform] = mapped_column(platform_enum, nullable=False)
    title: Mapped[str | None] = mapped_column(String(500), nullable=True)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    hashtags: Mapped[list[str]] = mapped_column(JSON, nullable=False, default=list)
    edited: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    clip: Mapped["Clip"] = relationship(back_populates="metadata_entries")  # noqa: F821
